export function getRelatedArticles(
  currentSlug: string,
  category: string,
  limit: number = 4,
) {
  return blogArticles
    .filter(
      (article) =>
        article.slug !== currentSlug && article.category === category,
    )
    .slice(0, limit);
}

export function getRelatedArticlesBySlug(slug: string, limit: number = 4) {
  const article = blogArticles.find((a) => a.slug === slug);
  if (!article) return [];
  return blogArticles
    .filter((a) => a.slug !== slug && a.category === article.category)
    .slice(0, limit);
}
